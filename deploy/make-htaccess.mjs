/*
 * Writes .htaccess with the site's security headers, for static hosting
 * (Hostinger web hosting, where there is no Node server to send them).
 * build.ps1 runs this after building the pages, so the allowed inline
 * scripts always match the pages being uploaded.
 *
 *   node deploy/make-htaccess.mjs           write .htaccess
 *   node deploy/make-htaccess.mjs --check   fail if .htaccess is out of date
 *
 * The Content-Security-Policy is the same one the Node server sends
 * (server/src/csp.js).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { sitePolicy, inlineScriptHashes } from "../server/src/csp.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, ".htaccess");

const pages = fs.readdirSync(ROOT).filter((f) => f.endsWith(".html")).sort();
const hashes = new Set();
const problems = [];
for (const page of pages) {
  const html = fs.readFileSync(path.join(ROOT, page), "utf8");
  inlineScriptHashes(html).forEach((h) => hashes.add(h));
  // onclick="…" and friends can't be allowed by a script hash.
  for (const [attr] of html.matchAll(/\son[a-z]+\s*=\s*["']/gi)) problems.push(`${page}: inline handler ${attr.trim()}`);
}
if (problems.length) {
  console.error("Inline event handlers would be blocked by the CSP. Move them into a script:\n  " + problems.join("\n  "));
  process.exit(1);
}

const headers = {
  "Content-Security-Policy": sitePolicy([...hashes].sort(), { upgradeInsecure: true }),
  // No includeSubDomains: other subdomains (e.g. email autodiscover) aren't ours to force onto HTTPS.
  "Strict-Transport-Security": "max-age=31536000",
  "X-Content-Type-Options": "nosniff",
  "X-Frame-Options": "SAMEORIGIN",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "Permissions-Policy": "camera=(), microphone=(), geolocation=()",
};

const text = [
  "# BEGIN Magzest security headers",
  "# Generated by deploy/make-htaccess.mjs from the built pages. Don't edit by",
  "# hand: run .\\build.ps1 instead. If the host already has a .htaccess, paste",
  "# this block into it rather than replacing the file.",
  "<IfModule mod_headers.c>",
  ...Object.entries(headers).map(([name, value]) => `  Header always set ${name} "${value}"`),
  "</IfModule>",
  "# END Magzest security headers",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) {
    console.error(".htaccess is out of date with the pages. Run: node deploy/make-htaccess.mjs");
    process.exit(1);
  }
  console.log(".htaccess is up to date.");
} else {
  fs.writeFileSync(OUT, text);
  console.log(`Wrote .htaccess (${hashes.size} inline script hashes from ${pages.length} pages).`);
}
